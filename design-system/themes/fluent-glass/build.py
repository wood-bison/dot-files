"""Generate portable web tokens and a Zed palette. Never installs or activates themes."""
import json
from pathlib import Path
from zed import make_style, validate_style
import icons
import terminal

ROOT = Path(__file__).resolve().parent

def contrast(a, b):
    def luminance(color):
        values = [int(color[i:i + 2], 16) / 255 for i in (1, 3, 5)]
        linear = [v / 12.92 if v <= .04045 else ((v + .055) / 1.055) ** 2.4 for v in values]
        return sum(v * w for v, w in zip(linear, (.2126, .7152, .0722)))
    x, y = sorted((luminance(a), luminance(b)))
    return (y + .05) / (x + .05)

def main():
    data = json.loads((ROOT / 'tokens.json').read_text())
    palettes = data['appearances']
    if palettes['light'].keys() != palettes['dark'].keys():
        raise ValueError('Appearance roles differ')
    if data['editor']['light'].keys() != data['editor']['dark'].keys():
        raise ValueError('Editor roles differ')
    pairs = [('ink', 'plate'), ('ink-body', 'plate'), ('ink-muted', 'plate'),
             ('accent-ink', 'plate'), ('ink', 'warm-soft'), ('sage', 'sage-soft'),
             ('code-ink', 'code-surface'), ('accent-contrast', 'accent')]
    for mode, tokens in palettes.items():
        for foreground, background in pairs:
            ratio = contrast(tokens['--fel-' + foreground], tokens['--fel-' + background])
            if ratio < 4.5:
                raise ValueError(f'{mode}: {foreground}/{background}: {ratio:.2f}')
    css = ['/* GENERATED by themes/fluent-glass/build.py. Edit tokens.json. */']
    for mode, tokens in palettes.items():
        selector = '[data-design="fluent-glass"]'
        if mode == 'dark':
            selector += '[data-theme="dark"]'
        css.append(selector + ' {')
        css += [f'  {key}: {value};' for key, value in tokens.items()]
        css += [f'  --fg-{key}: {value};' for key, value in data['shared'].items()]
        css.append('}')
    css += ['@media (prefers-reduced-transparency: reduce), (prefers-contrast: more) {',
            '  [data-design="fluent-glass"] { --fel-glass-functional: var(--fel-plate); --fel-glass-blur: 0px; --fel-ink-muted: var(--fel-ink); }', '}',
            '@media (prefers-reduced-motion: reduce) { [data-design="fluent-glass"] { --fg-motion-duration: 0ms; } }']
    themes = []
    styles = {}
    for mode, tokens in palettes.items():
        style = make_style(data, mode)
        minimum = validate_style(style, contrast)
        print(f'{mode}: {len(style)} style keys, {len(style["syntax"])} syntax scopes; minimum text contrast on editor states {minimum:.2f}:1')
        themes.append({'name': 'Fluent Glass ' + mode.title(), 'appearance': mode, 'style': style})
        styles[mode] = style
    output = ROOT / 'generated'
    output.mkdir(exist_ok=True)
    (output / 'fluent-glass.css').write_text('\n'.join(css) + '\n')
    (output / 'fluent-glass.json').write_text(json.dumps({'$schema': 'https://zed.dev/schema/themes/v0.2.0.json', 'name': 'Fluent Glass', 'author': 'Sergey', 'themes': themes}, indent=2) + '\n')
    for mode in palettes:
        terminal.generate(data, mode, styles[mode])
    icon_output = icons.generate(data)
    print(f'Validated both palettes; generated CSS, Zed, Ghostty, and icon themes in {icon_output}. Nothing installed.')

if __name__ == '__main__':
    main()
