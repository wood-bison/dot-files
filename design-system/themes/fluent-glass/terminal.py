"""Generate Ghostty themes from the validated Fluent Glass Zed style."""
from pathlib import Path


ROOT = Path(__file__).resolve().parents[3]


def generate(data, mode, style):
    """Write one opaque Ghostty theme using the Zed terminal palette."""
    ansi = [
        style['terminal.ansi.black'],
        style['terminal.ansi.red'],
        style['terminal.ansi.green'],
        style['terminal.ansi.yellow'],
        style['terminal.ansi.blue'],
        style['terminal.ansi.magenta'],
        style['terminal.ansi.cyan'],
        style['terminal.ansi.white'],
        style['terminal.ansi.bright_black'],
        style['terminal.ansi.bright_red'],
        style['terminal.ansi.bright_green'],
        style['terminal.ansi.bright_yellow'],
        style['terminal.ansi.bright_blue'],
        style['terminal.ansi.bright_magenta'],
        style['terminal.ansi.bright_cyan'],
        style['terminal.ansi.bright_white'],
    ]
    lines = [
        '# Generated by design-system/themes/fluent-glass/build.py; edit tokens.json.',
        f'# Fluent Glass {mode.title()} — opaque terminal palette.',
        f"background = {style['terminal.background']}",
        f"foreground = {style['terminal.foreground']}",
        f"cursor-color = {style['players'][0]['cursor']}",
        f"cursor-text = {style['terminal.background']}",
        f"selection-background = {style['editor.document_highlight.bracket_background']}",
        f"selection-foreground = {style['terminal.foreground']}",
        'background-opacity = 1',
        f"unfocused-split-fill = {data['appearances'][mode]['--fel-plate-muted']}",
        f"split-divider-color = {data['appearances'][mode]['--fel-line-strong']}",
    ]
    lines.extend(f'palette = {index}={color}' for index, color in enumerate(ansi))
    output = ROOT / 'ghostty' / 'themes' / f'fluent-glass-{mode}'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines) + '\n')
    return output
